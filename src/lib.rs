/// Information extracted from a `.d` dep-info file generated by rustc.
#[derive(Default, Debug, Clone, PartialEq, Eq)]
#[cfg_attr(test, derive(proptest_derive::Arbitrary))]
pub struct Contents {
    /// The source paths that the main target in the dep-info file depends on.
    ///
    /// The optional file lengths and checksums are parsed from `# checksum:...` comments.
    pub sources: HashMap<Source, Option<Metadata>>,

    /// The target paths named by rustc's dependency rules.
    pub targets: HashSet<Target>,

    /// The environment variables that the rustc compilation depends on.
    ///
    /// The key is the name of the env var and the value is its recorded value.
    /// `Some` means that the env var was set, and `None` means that the env var wasn't actually
    /// set and the compilation depends on it not being set.
    ///
    /// These are from the special `# env-dep:...` comments.
    pub env: HashMap<EnvKey, Option<EnvVal>>,
}

/// Path of an input.
///
/// # Invariants
///
/// - is not empty
/// - does not end with `\`
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct Source(String);

impl Source {
    /// Return the path text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consume this value and return the path text.
    pub fn into_string(self) -> String {
        self.0
    }
}

impl AsRef<str> for Source {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl Borrow<str> for Source {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

/// Why a path cannot be used as an input in dep-info.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum InvalidSource {
    /// The path is empty.
    #[error("input path must not be empty")]
    Empty,

    /// The path ends with a backslash, which Cargo interprets as an escape in output rules.
    #[error("input path must not end with `\\`")]
    TrailingBackslash,
}

#[cfg(test)]
impl proptest::arbitrary::Arbitrary for Source {
    type Parameters = ();
    type Strategy = proptest::strategy::BoxedStrategy<Self>;

    fn arbitrary_with(_: Self::Parameters) -> Self::Strategy {
        use proptest::prelude::*;

        any::<String>()
            .prop_filter("input path must be valid", |path| {
                !path.is_empty() && !path.ends_with('\\')
            })
            .prop_map(Self)
            .boxed()
    }
}

/// File length and checksum recorded for an input by a `# checksum:...` comment.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(test, derive(proptest_derive::Arbitrary))]
pub struct Metadata {
    /// Length of the input file in bytes when its checksum was recorded.
    pub file_len: u64,
    /// Checksum of the input file.
    pub checksum: Checksum,
}

