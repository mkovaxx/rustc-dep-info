/// Information extracted from a `.d` dep-info file generated by rustc.
///
/// The collections retain insertion order for printing.
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
#[derive(Default, Debug, Clone, PartialEq, Eq)]
pub struct Contents {
    /// The source paths that the main target in the dep-info file depends on.
    ///
    /// The optional file lengths and checksums are parsed from `# checksum:...` comments.
    pub sources: IndexMap<Source, Option<Metadata>>,

    /// The target paths named by rustc's dependency rules.
    pub targets: IndexSet<Target>,

    /// The environment variables that the rustc compilation depends on.
    ///
    /// The key is the name of the env var and the value is its recorded value.
    /// `Some` means that the env var was set, and `None` means that the env var wasn't actually
    /// set and the compilation depends on it not being set.
    ///
    /// These are from the special `# env-dep:...` comments.
    pub env: IndexMap<EnvKey, Option<EnvVal>>,
}

/// Path of a source.
///
/// # Invariants
///
/// - is not empty
/// - does not end with `\`
/// - does not contain `\n` or `\r`
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct Source(pub(crate) String);

/// A decoded source path violates a [`Source`] invariant.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum SourceError {
    /// The path is empty.
    #[error("source path is empty")]
    Empty,
    /// The path ends with a backslash.
    #[error("source path ends with a backslash")]
    EndsWithBackslash,
    /// The path contains a newline or carriage return.
    #[error("source path contains a line break")]
    ContainsLineBreak,
}

impl Source {
    /// Construct a source from decoded path text, preserving it exactly.
    ///
    /// Spaces and backslashes are literal; dep-info escapes are not decoded.
    ///
    /// # Errors
    ///
    /// Rejects empty paths, paths ending with a backslash, and paths containing
    /// a newline or carriage return.
    pub fn new(value: impl Into<String>) -> Result<Self, SourceError> {
        let value = value.into();
        if value.is_empty() {
            return Err(SourceError::Empty);
        }
        if value.ends_with('\\') {
            return Err(SourceError::EndsWithBackslash);
        }
        if value.contains(['\n', '\r']) {
            return Err(SourceError::ContainsLineBreak);
        }
        Ok(Self(value))
    }

    /// Return the path text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consume this value and return the path text.
    pub fn into_string(self) -> String {
        self.0
    }
}

impl AsRef<str> for Source {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl Borrow<str> for Source {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

#[cfg(feature = "arbitrary")]
impl<'a> arbitrary::Arbitrary<'a> for Source {
    fn arbitrary(u: &mut arbitrary::Unstructured<'a>) -> arbitrary::Result<Self> {
        let mut path = String::arbitrary(u)?.replace(['\n', '\r'], "_");
        if path.is_empty() || path.ends_with('\\') {
            path.push('x');
        }
        Self::new(path).map_err(|_| arbitrary::Error::IncorrectFormat)
    }
}

/// File length and checksum recorded for a source by a `# checksum:...` comment.
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Metadata {
    /// Length of the source file in bytes when its checksum was recorded.
    pub file_len: u64,
    /// Digest of the source file.
    pub digest: Digest,
}

/// Path of a target.
///
/// # Invariants
///
/// - is not empty
/// - does not contain `": "` (which Cargo's parser treats as the end of a target path)
/// - does not contain `\n` or `\r`
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct Target(pub(crate) String);

/// A decoded target path violates a [`Target`] invariant.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum TargetError {
    /// The path is empty.
    #[error("target path is empty")]
    Empty,
    /// The path contains the rule separator `": "`.
    #[error("target path contains a rule separator")]
    ContainsRuleSeparator,
    /// The path contains a newline or carriage return.
    #[error("target path contains a line break")]
    ContainsLineBreak,
}

impl Target {
    /// Construct a target from decoded path text, preserving it exactly.
    ///
    /// Dep-info escapes are not decoded.
    ///
    /// # Errors
    ///
    /// Rejects empty paths and paths containing `": "`, a newline, or a carriage return.
    pub fn new(value: impl Into<String>) -> Result<Self, TargetError> {
        let value = value.into();
        if value.is_empty() {
            return Err(TargetError::Empty);
        }
        if value.contains(": ") {
            return Err(TargetError::ContainsRuleSeparator);
        }
        if value.contains(['\n', '\r']) {
            return Err(TargetError::ContainsLineBreak);
        }
        Ok(Self(value))
    }

    /// Return the path text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consume this value and return the path text.
    pub fn into_string(self) -> String {
        self.0
    }
}

impl AsRef<str> for Target {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl Borrow<str> for Target {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

#[cfg(feature = "arbitrary")]
impl<'a> arbitrary::Arbitrary<'a> for Target {
    fn arbitrary(u: &mut arbitrary::Unstructured<'a>) -> arbitrary::Result<Self> {
        let mut path = String::arbitrary(u)?
            .replace(['\n', '\r'], "_")
            .replace(": ", ":");
        if path.is_empty() {
            path.push('x');
        }
        Self::new(path).map_err(|_| arbitrary::Error::IncorrectFormat)
    }
}

/// A source-file checksum.
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
pub enum Digest {
    /// A SHA-256 digest.
    Sha256([u8; 32]),
    /// A BLAKE3 digest.
    Blake3([u8; 32]),
}

impl Digest {
    /// Return the raw digest bytes.
    pub fn value(&self) -> &[u8; 32] {
        match self {
            Self::Sha256(value) | Self::Blake3(value) => value,
        }
    }
}

