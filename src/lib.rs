/// Information extracted from a `.d` dep-info file generated by rustc.
///
/// The collections retain insertion order for printing.
#[derive(Default, Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
pub struct Contents {
    /// The source paths that the main target in the dep-info file depends on.
    ///
    /// The optional file lengths and checksums are parsed from `# checksum:...` comments.
    pub sources: IndexMap<Source, Option<Metadata>>,

    /// The target paths named by rustc's dependency rules.
    pub targets: IndexSet<Target>,

    /// The environment variables that the rustc compilation depends on.
    ///
    /// The key is the name of the env var and the value is its recorded value.
    /// `Some` means that the env var was set, and `None` means that the env var wasn't actually
    /// set and the compilation depends on it not being set.
    ///
    /// These are from the special `# env-dep:...` comments.
    pub env: IndexMap<EnvKey, Option<EnvVal>>,
}

/// Path of an input.
///
/// # Invariants
///
/// - is not empty
/// - does not end with `\`
/// - does not contain `\n` or `\r`
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct Source(String);

impl Source {
    /// Return the path text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consume this value and return the path text.
    pub fn into_string(self) -> String {
        self.0
    }
}

impl AsRef<str> for Source {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl Borrow<str> for Source {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

/// Why a path cannot be used as an input in dep-info.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum InvalidSource {
    /// The path is empty.
    #[error("input path must not be empty")]
    Empty,

    /// The path ends with a backslash, which Cargo interprets as an escape in output rules.
    #[error("input path must not end with `\\`")]
    TrailingBackslash,

    /// The path contains a line break.
    #[error("input path must not contain `\\n` or `\\r`")]
    ContainsLineBreak,
}

#[cfg(feature = "arbitrary")]
impl<'a> arbitrary::Arbitrary<'a> for Source {
    fn arbitrary(u: &mut arbitrary::Unstructured<'a>) -> arbitrary::Result<Self> {
        let mut path = String::arbitrary(u)?.replace(['\n', '\r'], "_");
        if path.is_empty() || path.ends_with('\\') {
            path.push('x');
        }
        Ok(Self(path))
    }
}

/// File length and checksum recorded for an input by a `# checksum:...` comment.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
pub struct Metadata {
    /// Length of the input file in bytes when its checksum was recorded.
    pub file_len: u64,
    /// Checksum of the input file.
    pub checksum: Checksum,
}

/// Path of an output.
///
/// # Invariants
///
/// - is not empty
/// - does not contain `": "` (which Cargo's parser treats as the end of an output path)
/// - does not contain `\n` or `\r`
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct Target(String);

impl Target {
    /// Return the path text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consume this value and return the path text.
    pub fn into_string(self) -> String {
        self.0
    }
}

impl AsRef<str> for Target {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl Borrow<str> for Target {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

/// Why a path cannot be used as an output in dep-info.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum InvalidTarget {
    /// The path is empty.
    #[error("output path must not be empty")]
    Empty,

    /// The path contains the `": "` output rule separator.
    #[error("output path must not contain `: `")]
    ContainsRuleSeparator,

    /// The path contains a line break.
    #[error("output path must not contain `\\n` or `\\r`")]
    ContainsLineBreak,
}

#[cfg(feature = "arbitrary")]
impl<'a> arbitrary::Arbitrary<'a> for Target {
    fn arbitrary(u: &mut arbitrary::Unstructured<'a>) -> arbitrary::Result<Self> {
        let mut path = String::arbitrary(u)?.replace(['\n', '\r'], "_");
        if path.is_empty() {
            path.push('x');
        }
        Ok(Self(path.replace(": ", ":")))
    }
}

/// A source-file checksum encoded as `algorithm=hex_digest`.
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
pub struct Checksum {
    algo: ChecksumAlgo,
    /// If the algorithm uses fewer than 32 bytes, then the remaining bytes will be zero.
    value: [u8; 32],
}

impl Checksum {
    /// Construct a checksum from its algorithm and digest bytes.
    pub fn new(algo: ChecksumAlgo, value: [u8; 32]) -> Self {
        Self { algo, value }
    }

    /// Return the algorithm used for this checksum.
    pub fn algo(&self) -> ChecksumAlgo {
        self.algo
    }

    /// Return the raw digest bytes.
    pub fn value(&self) -> &[u8; 32] {
        &self.value
    }
}

/// Some algorithms are here to ensure compatibility with possible rustc outputs.
/// The presence of an algorithm here is not a suggestion that it's fit for use.
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[cfg_attr(feature = "arbitrary", derive(arbitrary::Arbitrary))]
pub enum ChecksumAlgo {
    Sha256,
    Blake3,
}

impl ChecksumAlgo {
    fn hash_len(&self) -> usize {
        match self {
            ChecksumAlgo::Sha256 | ChecksumAlgo::Blake3 => 32,
        }
    }
}

/// An error parsing a checksum algorithm or digest.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
pub enum InvalidChecksum {
    #[error("algorithm portion incorrect, expected `sha256`, or `blake3`")]
    InvalidChecksumAlgo,
    #[error("expected {} hexadecimal digits in checksum portion", .0.hash_len() * 2)]
    InvalidChecksum(ChecksumAlgo),
    #[error("expected a string with format \"algorithm=hex_checksum\"")]
    InvalidFormat,
}

