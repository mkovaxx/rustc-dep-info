//! Parse, print, and manipulate dep-info files used by `rustc` and Cargo.
//!
//! [`Contents`] holds source and target paths, tracked environment variables, and optional file
//! lengths and checksums. Parse dep-info text with [`str::parse`], then print
//! it with `to_string()` or the [`Display`](std::fmt::Display) implementation.
//!
//! # Example
//!
//! ```
//! let info: rustc_dep_info::Contents = r#"
//! app: src/main.rs
//! ## env-dep:MODE=debug
//! "#
//! .parse()?;
//!
//! assert!(info.sources.contains_key("src/main.rs"));
//! assert_eq!(info.env.get("MODE"), Some(&Some("debug".into())));
//! # Ok::<(), rustc_dep_info::ParseError>(())
//! ```
//!
//! Based on `rustc` and `cargo` sources. See the repository's `UPSTREAM.md` for source provenance.

